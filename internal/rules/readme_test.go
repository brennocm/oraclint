package rules

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

var update = flag.Bool("update", false, "rewrite generated files (README rule table)")

const (
	tableStart = "<!-- rules:start (generated by `make golden-update`, do not edit) -->"
	tableEnd   = "<!-- rules:end -->"
)

// ruleTable renders the README rule table from the registry.
func ruleTable() string {
	var b strings.Builder
	b.WriteString("| ID | Severity | Target | Status | Title |\n|---|---|---|---|---|\n")
	for _, r := range All() {
		m := r.Metadata()
		var targets []string
		for _, k := range m.Targets {
			targets = append(targets, k.String())
		}
		fmt.Fprintf(&b, "| [%s](docs/rules/%s.md) | %s | %s | %s | %s |\n",
			m.ID, m.ID, m.Severity, strings.Join(targets, ", "), m.Status, m.Title)
	}
	return b.String()
}

// TestGoldenReadmeRuleTable fails when the README table is out of date with
// the registry; `make golden-update` regenerates it.
func TestGoldenReadmeRuleTable(t *testing.T) {
	path := filepath.Join("..", "..", "README.md")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	readme := string(data)
	start := strings.Index(readme, tableStart)
	end := strings.Index(readme, tableEnd)
	if start < 0 || end < start {
		t.Fatalf("README.md lacks the %q / %q markers", tableStart, tableEnd)
	}
	want := tableStart + "\n" + ruleTable() + tableEnd
	got := readme[start : end+len(tableEnd)]
	if got == want {
		return
	}
	if *update {
		if err := os.WriteFile(path, []byte(readme[:start]+want+readme[end+len(tableEnd):]), 0o600); err != nil {
			t.Fatal(err)
		}
		return
	}
	t.Error("README rule table is out of date; run `make golden-update`")
}
